-- Writes addons/cute/stats.js from the addon's own code, so the page's stat explorer and the mock window are the
-- registry and the window's defaults, not a copy of them: every stat's id, label, short column label, category, kind,
-- default visibility, hint, list size or pip count, formatter and column width (Stats.lua, UI.lua), the default
-- columns per page (UI.DEFAULT_COLS), the other categories' stats a page offers beside its own (UI.PAGE_EXTRA: the
-- Officers page's raids, bosses, dungeons seen and consumables), the categories in order, and the rules' thresholds
-- as Settings shows them with their bounds and defaults (Rules.lua R.TUNE and R.RULES) and how many members it takes
-- to learn an enchant (Stats.lua S.VOICES), so the mock's Rules section cannot drift from the window's. The fifth category, game
-- (Statistics), is in the list with its label but holds no stat here: its stats are defined at login from what the
-- client reports (Stats.lua ProbeGame), and the discovered ones (bosses, instances, factions: Stats.lua's found) from
-- what the guild meets in play, so a page mock that shows the Statistics tab brings its own categories and numbers.
--   luajit tools/cute/page_stats.lua
-- What a stat would tell a member (Stats.lua reveals, rv here), what a discovered category does (CUTE_CAT_RV), a stat
-- nobody sets (fixed, fx here) and the gaps Ready may count (CUTE_READY) come too, so the mock keeps a stat with the one
-- it would give away as the window does.
-- build.py runs it; the mock reads window.CUTE_STATS, window.CUTE_COLS, window.CUTE_CATS, window.CUTE_TUNE,
-- window.CUTE_RULES, window.CUTE_VOICES, window.CUTE_CAT_RV and window.CUTE_READY.
local HERE = (arg and arg[0] and arg[0]:match("^(.*)/") or ".")
local env = setmetatable({}, { __index = _G })
env._G = env
env.C_Timer = { After = function() end }
local C = {}
-- Core.lua's helpers the registry leans on, without the game
local core = assert(loadstring(io.open(HERE .. "/Cute/Core.lua"):read("*a"), "@Core.lua"))
env.CreateFrame = function() return setmetatable({}, { __index = function() return function() end end }) end
env.SlashCmdList = {}
setfenv(core, env)
core("Cute", C)
-- the module registry, which UI.lua registers the dashboard's pages with
local modules = assert(loadstring(io.open(HERE .. "/Cute/Modules.lua"):read("*a"), "@Modules.lua"))
setfenv(modules, env)
modules("Cute", C)
local stats = assert(loadstring(io.open(HERE .. "/Cute/Stats.lua"):read("*a"), "@Stats.lua"))
setfenv(stats, env)
stats("Cute", C)
-- UI.lua only defines things at load; it is read for the default columns and the short labels
local ui = assert(loadstring(io.open(HERE .. "/Cute/UI.lua"):read("*a"), "@UI.lua"))
setfenv(ui, env)
ui("Cute", C)
assert(C.UI and C.UI.DEFAULT_COLS and C.UI.SHORT and C.UI.PAGE_EXTRA, "UI.lua no longer exports DEFAULT_COLS, SHORT and PAGE_EXTRA")
-- Rules.lua only defines things at load too; it is read for the thresholds
local rules = assert(loadstring(io.open(HERE .. "/Cute/Rules.lua"):read("*a"), "@Rules.lua"))
setfenv(rules, env)
rules("Cute", C)
assert(C.Rules and C.Rules.TUNE and C.Rules.RULES and C.Stats.VOICES, "Rules.lua no longer exports TUNE and RULES, or Stats.lua VOICES")

local function q(s) return '"' .. tostring(s):gsub("\\", "\\\\"):gsub('"', '\\"') .. '"' end
local function short(d) return C.UI.SHORT[d.id] or d.label end
-- the width a column takes in the window: UI.lua's colWidth, mirrored (it is local there)
local function colWidth(d)
  if d.kind == "flag" then return 44 end
  if d.kind == "text" then return 110 end
  if d.kind == "list" then return 62 end
  if d.kind == "pips" then return math.max(36, 8 + 7 * (d.pips or 8)) end
  if d.fmt == C.Stats.FmtHours then return 70 end
  return math.max(56, 12 + #short(d) * 7)
end
local function fmtName(d)
  if d.fmt == C.Stats.FmtHours then return q("hours") end
  if d.fmt == C.Stats.FmtPct then return q("pct") end
  if d.fmt == C.Stats.FmtGold then return q("gold") end
  if d.fmt == C.Stats.FmtReady then return q("ready") end
  if d.fmt == C.Stats.FmtOrDash then return q("ordash") end
  return "null"
end

-- a policy id as the page keys it: a stat's own, a discovered category's "stats:<kind>" ("gc_bosses" in the window)
local function key(id) local f = id:match("^gc_(%l+)$"); return q(f and ("stats:" .. f) or id) end
local function keys(list) local t = {}; for i, id in ipairs(list or {}) do t[i] = key(id) end return "[" .. table.concat(t, ", ") .. "]" end
local out = { "// generated by tools/cute/page_stats.lua from Cute/Stats.lua and Cute/UI.lua; do not edit", "window.CUTE_STATS = [" }
for _, d in ipairs(C.Stats.list) do
  local n = d.kind == "list" and #d.of or d.kind == "pips" and (d.pips or 8) or nil
  -- (rv: what the stat would tell a member, which it goes the way of: Stats.lua reveals; fx: nobody's to set, Everyone
  -- always: Stats.lua fixed)
  out[#out + 1] = string.format("  { id: %s, label: %s, short: %s, cat: %s, kind: %s, vis: %s, hint: %s, n: %s, fmt: %s, w: %d%s%s },",
    q(d.id), q(d.label), q(short(d)), q(d.cat), q(d.kind), q(d.default), d.hint and q(d.hint) or "null", n and tostring(n) or "null", fmtName(d), colWidth(d),
    d.reveals and (", rv: " .. keys(d.reveals)) or "", d.fixed and ", fx: true" or "")
end
out[#out + 1] = "];"
-- what a discovered category tells beyond its own (its counts: Stats.lua S.CatReveals); the game's categories' children
-- are the page's own
local catRv = {}
for _, f in ipairs(C.Stats.FOUND) do
  local rv = C.Stats.CatReveals("gc_" .. f[1])
  if rv then catRv[#catRv + 1] = string.format("%s: %s", key("gc_" .. f[1]), keys(rv)) end
end
out[#out + 1] = "window.CUTE_CAT_RV = { " .. table.concat(catRv, ", ") .. " };"
-- the gaps Ready may count, each only while everyone may see it (Stats.lua S.READY_INPUTS)
out[#out + 1] = "window.CUTE_READY = " .. keys(C.Stats.READY_INPUTS) .. ";"
out[#out + 1] = "window.CUTE_COLS = {"
for _, page in ipairs({ "race", "prog", "officers" }) do
  local ids = {}
  for _, id in ipairs(C.UI.DEFAULT_COLS[page]) do
    assert(C.Stats.byId[id], "UI.DEFAULT_COLS names an unknown stat: " .. id)
    ids[#ids + 1] = q(id)
  end
  out[#out + 1] = string.format("  %s: [%s],", page, table.concat(ids, ", "))
end
out[#out + 1] = "};"
out[#out + 1] = "window.CUTE_EXTRA = {"
for _, page in ipairs({ "officers" }) do
  local ids = {}
  for _, id in ipairs(C.UI.PAGE_EXTRA[page] or {}) do
    assert(C.Stats.byId[id], "UI.PAGE_EXTRA names an unknown stat: " .. id)
    ids[#ids + 1] = q(id)
  end
  out[#out + 1] = string.format("  %s: [%s],", page, table.concat(ids, ", "))
end
out[#out + 1] = "};"
local cats = {}
for _, cat in ipairs(C.Stats.CATS) do cats[#cats + 1] = string.format("[%s, %s]", q(cat), q(C.Stats.CAT_LABEL[cat])) end
out[#out + 1] = "window.CUTE_CATS = [" .. table.concat(cats, ", ") .. "];"
-- each threshold as Settings shows it: [name, label, lowest, highest, step, how it reads, what it does, the module whose
-- section holds it], as R.TUNE has them; the defaults; the members an enchant slot takes
local function n(v) return v == nil and "null" or (v == math.floor(v) and string.format("%d", v) or (string.format("%.4f", v):gsub("0+$", ""))) end
out[#out + 1] = "window.CUTE_TUNE = ["
for _, t in ipairs(C.Rules.TUNE) do
  out[#out + 1] = string.format("  [%s, %s, %s, %s, %s, %s, %s, %s],", q(t[1]), q(t[2]), n(t[3]), n(t[4]), n(t[5]), t[6] and q(t[6]) or "null", q(t[7]), t[8] and q(t[8]) or "null")
end
out[#out + 1] = "];"
local defaults = {}
for _, t in ipairs(C.Rules.TUNE) do
  assert(C.Rules.RULES[t[1]] ~= nil, "R.TUNE names a rule R.RULES has no default for: " .. t[1])
  defaults[#defaults + 1] = string.format("%s: %s", t[1], n(C.Rules.RULES[t[1]]))
end
out[#out + 1] = "window.CUTE_RULES = { " .. table.concat(defaults, ", ") .. " };"
out[#out + 1] = "window.CUTE_VOICES = " .. n(C.Stats.VOICES) .. ";"
local f = assert(io.open(HERE .. "/../../addons/cute/stats.js", "w"))
f:write(table.concat(out, "\n") .. "\n")
f:close()
print("stats.js: " .. #C.Stats.list .. " stats")
